import test from 'node:test';
import assert from 'node:assert/strict';
import {interpret,CAPABILITIES} from '../copilota/engine.mjs';
test('no input returns help',()=>assert.equal(interpret(' ').kind,'help'));
test('trip draft needs confirmation',()=>{const x=interpret('Carico container ABCD1234567');assert.equal(x.kind,'trip_draft');assert.equal(x.container,'ABCD1234567');assert.equal(x.requiresConfirmation,true);});
test('never fabricates a tariff',()=>{const x=interpret('Quanto costa la tariffa?');assert.equal(x.kind,'tariff_help');assert.doesNotMatch(x.message,/€\s*\d/);});
test('customer requests require approval',()=>assert.equal(interpret('Nuovo cliente Google Maps').requiresConfirmation,true));
test('port info uses official sources',()=>assert.match(interpret('Booking porto').message,/ufficiali/));
test('secret warnings',()=>assert.match(interpret('password').message,/Non inserire password/));
test('all intents are known',()=>{for(const input of ['ciao','viaggio','cliente','tariffa','porto','assistenza'])assert.ok(CAPABILITIES.includes(interpret(input).kind));});
